NEW_CATS = [CAT_LEGAL, CAT_FIN, CAT_LOGIC, CAT_MACRO, CAT_ORG, CAT_CONSUMER, CAT_MINDSET]


def load(path: Path):
    raw = path.read_text(encoding='utf-8')
    vocab = json.loads(re.search(r'window\.VOCAB=(\[.*?\]);', raw, re.S).group(1))
    cats = json.loads(re.search(r'window\.CATEGORIES=(\[.*?\]);', raw, re.S).group(1))
    return vocab, cats, raw


def dump(path: Path, vocab, cats):
    now = datetime.now().isoformat(timespec='microseconds')
    body = (
        f'/* build: {now} */\n'
        f'window.VOCAB={json.dumps(vocab, ensure_ascii=False, separators=(",", ":"))};\n'
        f'window.CATEGORIES={json.dumps(cats, ensure_ascii=False, separators=(",", ":"))};\n'
    )
    path.write_text(body, encoding='utf-8', newline='\r\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default='data.js')
    ap.add_argument('--out', default=None)
    ap.add_argument('--apply', action='store_true')
    a = ap.parse_args()

    src = Path(a.src)
    out = Path(a.out) if a.out else src
    vocab, cats, _ = load(src)
    n0 = len(vocab)

    # 重复校验：同步内去重
    seen = Counter(c[1] for c in ENTRIES)
    inner_dup = [w for w, n in seen.items() if n > 1]
    if inner_dup:
        print('!! 脚本内重复词，请先修正：', inner_dup)
        return 1

    existing = {e['word'] for e in vocab}
    new_id = max(e['id'] for e in vocab)
    added, skipped = [], []
    for cat, word, syn, mean, ex, scene in ENTRIES:
        if word in existing:
            skipped.append(word)
            continue
        new_id += 1
        added.append({'id': new_id, 'cat': cat, 'word': word, 'syn': syn,
                      'mean': mean, 'example': ex, 'scene': scene, 'tab': 'vocab'})
        existing.add(word)

    print('=' * 78)
    print(f'源文件 {src}   补缺前 {n0} 条 / {len(cats)} 分类')
    print('=' * 78)
    per = Counter(e['cat'] for e in added)
    for c in NEW_CATS:
        print(f'  {c:<20s} 计划 {sum(1 for x in ENTRIES if x[0] == c):>2d}  '
              f'实补 {per.get(c, 0):>2d}')
    print('-' * 78)
    if skipped:
        print(f'  跳过（库中已有，遵循"一词一分类"）{len(skipped)} 个：')
        print('   ', '、'.join(skipped))
    print(f'  实际新增 {len(added)} 条，id {n0 and added[0]["id"] if added else 0}'
          f'–{added[-1]["id"] if added else 0}')
    print(f'  补缺后 {n0 + len(added)} 条 / {len(cats) + len(NEW_CATS)} 分类')
    print('=' * 78)
    for e in added:
        print(f'  +id{e["id"]:<5d} [{e["cat"]}] {e["word"]}')
        print(f'          syn : {e["syn"]}')
        print(f'          mean: {e["mean"]}')

    if not a.apply:
        print('\n（干跑，未落盘。加 --apply 执行）')
        return 0

    vocab = vocab + added
    cats = list(cats)
    for c in NEW_CATS:
        if c not in cats:
            cats.append(c)

    # 落盘前自检
    assert len({e['id'] for e in vocab}) == len(vocab), 'id 重复'
    assert all(e['cat'] in cats for e in vocab), '分类越界'
    assert len({e['word'] for e in vocab}) == len(vocab), 'word 重复'
    ct = {}
    for e in vocab:
        if e.get('tab'):
            ct.setdefault(e['cat'], set()).add(e['tab'])
    mixed = {k: v for k, v in ct.items() if len(v) > 1}
    assert not mixed, f'分类内 tab 混用: {mixed}'

    bak = src.parent / 'build' / 'backup' / f'data_prefix_{datetime.now():%Y%m%d_%H%M%S}.js'
    bak.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, bak)
    dump(out, vocab, cats)
    print(f'\n已备份 → {bak}')
    print(f'已写入 → {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
